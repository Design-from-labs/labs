#!/usr/bin/env node
// Builds every generated input from the canonical content, after validating
// it (docs/contract.md):
//
//   .generated/site-data.json        what the pages render
//   .generated/items/<item>/...      published variants as files, for demos
//   .generated/Demos.astro           static imports of every demo (islands)
//   .generated/theme.css             tokens + component cssVars, light/dark
//   .generated/dep-index.json        alias fallbacks for cross-item imports
//   public/r/*.json                  the shadcn registry (/r/registry.json too)
//   public/schemas/*.json            the contract schemas, at their $id URLs
//   packages/react/src/generated/    sources of the @designfrom/react library
//   packages/react/package.json      its "exports" map
//
// Fails (exit 1) on any validation error. Missing previews are warnings here
// and errors in `pnpm validate:content`.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import {
  includeBeta,
  isPublished,
  kindOf,
  loadComponents,
  loadCredits,
  loadProjects,
  loadSources,
  ROOT,
} from "./lib/content.mjs";
import { npmSubpath } from "./lib/naming.mjs";
import { registryIndex, siteData, targetPath } from "./lib/publish.mjs";
import { validateContent } from "./lib/validate.mjs";

const GEN = join(ROOT, ".generated");
const PUBLIC_R = join(ROOT, "public", "r");
const PKG = join(ROOT, "packages", "react");
const PKG_GEN = join(PKG, "src", "generated");

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const id = (name) => `D_${name.replace(/[^a-zA-Z0-9]/g, "_")}`;

function cssBlock(selector, vars) {
  const lines = Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

/** Tokens from the theme item plus every published item's own cssVars. */
function themeCss(published) {
  const light = {};
  const dark = {};
  const theme = {};
  const ordered = [...published].sort(
    (a, b) =>
      (a.item.type === "registry:theme" ? -1 : 0) -
      (b.item.type === "registry:theme" ? -1 : 0),
  );
  for (const { item } of ordered) {
    if (!item.cssVars || item.type === "registry:base") {
      continue;
    }
    Object.assign(light, item.cssVars.light);
    Object.assign(dark, item.cssVars.dark);
    Object.assign(theme, item.cssVars.theme ?? {});
  }
  return [
    "/* Generated by scripts/prepare-content.mjs from the published registry items. Do not edit. */",
    cssBlock(":root", light),
    `@media (prefers-color-scheme: dark) {\n${cssBlock(':root:not([data-theme="light"])', dark).replace(/^/gm, "  ").trimEnd()}\n}\n`,
    cssBlock(':root[data-theme="dark"], .dark', dark),
    Object.keys(theme).length ? cssBlock("@theme inline", theme) : "",
  ].join("\n");
}

function main() {
  const components = loadComponents();
  const sources = loadSources();
  const credits = loadCredits();
  const { errors, warnings } = validateContent(components, sources, credits, {
    previews: false,
  });
  for (const w of warnings) {
    process.stdout.write(`warning: ${w}\n`);
  }
  if (errors.length > 0) {
    for (const e of errors) {
      process.stderr.write(`error: ${e}\n`);
    }
    process.stderr.write(
      `prepare-content: ${errors.length} validation error(s).\n`,
    );
    process.exitCode = 1;
    return;
  }

  const data = siteData(components, credits, loadProjects());
  const { published } = data;
  rmSync(GEN, { recursive: true, force: true });
  rmSync(PUBLIC_R, { recursive: true, force: true });
  rmSync(PKG_GEN, { recursive: true, force: true });

  // The registry.
  for (const { item } of published) {
    write(join(PUBLIC_R, `${item.name}.json`), json(item));
  }
  write(join(PUBLIC_R, "registry.json"), json(registryIndex(published)));
  rmSync(join(ROOT, "public", "previews"), { recursive: true, force: true });
  for (const entry of components) {
    const preview = entry.meta?.preview;
    if (
      preview &&
      (entry.meta.status === "ready" ||
        (includeBeta() && entry.meta.status === "beta")) &&
      existsSync(join(entry.dir, preview))
    ) {
      write(
        join(ROOT, "public", "previews", `${entry.name}.webp`),
        readFileSync(join(entry.dir, preview)),
      );
    }
  }
  for (const schema of ["meta.schema.json", "labs-registry-item.schema.json"]) {
    write(
      join(ROOT, "public", "schemas", schema),
      readFileSync(join(ROOT, "schemas", schema), "utf8"),
    );
  }

  // Demo sources: each published variant as files, plus its demo.
  const depIndex = {};
  const demoImports = [];
  for (const { item, entry, variant } of published) {
    const dir = join(GEN, "items", item.name);
    for (const file of item.files ?? []) {
      const target = targetPath(file);
      write(join(dir, target), file.content);
      const key = target.replace(/\.(tsx?|css)$/, "");
      if (entry.meta.defaultVariant === variant.name || !depIndex[key]) {
        depIndex[key] = relative(ROOT, join(dir, target));
      }
    }
    const view = data.entries
      .find((e) => e.name === entry.meta.name)
      ?.variants.find((v) => v.name === variant.name);
    if (view?.demo) {
      write(
        join(dir, "__demo.tsx"),
        readFileSync(join(entry.dir, view.demo), "utf8"),
      );
      demoImports.push(item.name);
    }
  }
  write(join(GEN, "dep-index.json"), json(depIndex));
  write(
    join(GEN, "Demos.astro"),
    [
      "---",
      "// Generated by scripts/prepare-content.mjs. Static imports, so Astro can",
      "// hydrate each demo as its own lazy island.",
      ...demoImports.map(
        (name) => `import ${id(name)} from "./items/${name}/__demo.tsx";`,
      ),
      "interface Props { item: string; hydrate?: boolean }",
      "const { item, hydrate = false } = Astro.props;",
      "---",
      ...demoImports.map(
        (name) =>
          `{item === ${JSON.stringify(name)} && (hydrate ? <${id(name)} client:visible /> : <${id(name)} />)}`,
      ),
      "",
    ].join("\n"),
  );
  write(join(GEN, "theme.css"), themeCss(published));
  const { published: _omit, ...pageData } = data;
  write(join(GEN, "site-data.json"), json(pageData));

  // The npm library sources (decision 0009). Ready variants only, even on a
  // build that shows beta entries on the site.
  const library = published.filter(({ entry, variant }) =>
    isPublished(entry.meta, variant),
  );
  const exportsMap = {};
  const entries = [];
  const takenDefaults = new Set();
  for (const { item, entry, variant, exports } of library) {
    const kind = kindOf(entry.meta);
    if (!["component", "hook", "lib"].includes(kind)) {
      continue;
    }
    const subpath = npmSubpath({
      component: entry.meta.name,
      style: variant.style,
      primitive: variant.primitive,
      iconSet: variant.iconSet,
    });
    const dir = join(PKG_GEN, subpath);
    for (const file of item.files) {
      const name = file.path.split("/").pop();
      const utils = relative(dir, join(PKG, "src", "lib", "utils")).replaceAll(
        "\\",
        "/",
      );
      const content = file.content
        .replaceAll(
          '"@/lib/utils"',
          `"${utils.startsWith(".") ? utils : `./${utils}`}"`,
        )
        .replace(
          /"@\/(?:components\/ui|components|hooks|lib)\/([a-z0-9-]+)"/g,
          (_, dep) => `"./${dep}"`,
        );
      write(join(dir, name), content);
    }
    const modules = item.files.map(
      (f) =>
        `./${f.path
          .split("/")
          .pop()
          .replace(/\.(tsx?)$/, "")}`,
    );
    write(
      join(dir, "index.ts"),
      `${modules.map((m) => `export * from "${m}";`).join("\n")}\n`,
    );
    entries.push(subpath);
    exportsMap[`./${subpath}`] = {
      types: `./dist/${subpath}/index.d.ts`,
      import: `./dist/${subpath}/index.js`,
    };
    if (variant.iconSet === "lucide") {
      exportsMap[`./${subpath}/lucide`] = exportsMap[`./${subpath}`];
    }
    void exports;
  }
  // @designfrom/react/<component> is the default variant when that path is free.
  for (const { entry, variant } of library) {
    const name = entry.meta.name;
    if (
      variant.name !== entry.meta.defaultVariant ||
      exportsMap[`./${name}`] ||
      takenDefaults.has(name)
    ) {
      continue;
    }
    if (!["component", "hook", "lib"].includes(kindOf(entry.meta))) {
      continue;
    }
    const subpath = npmSubpath({
      component: name,
      style: variant.style,
      primitive: variant.primitive,
      iconSet: variant.iconSet,
    });
    takenDefaults.add(name);
    exportsMap[`./${name}`] = exportsMap[`./${subpath}`];
  }
  exportsMap["./styles.css"] = "./dist/styles.css";
  exportsMap["./package.json"] = "./package.json";
  write(join(PKG_GEN, "entries.json"), json(entries.sort()));
  write(join(PKG_GEN, "theme.css"), themeCss(library));
  // Attribution for everything the library ships (the per-file headers are
  // stripped by the bundler, so the notice travels in NOTICE.md instead).
  const notice = [
    "# Notices",
    "",
    "Generated from the published registry items. Credits: https://labs.designfrom.com/credits",
    "",
  ];
  const seen = new Set();
  for (const { entry } of library) {
    const m = entry.meta;
    if (seen.has(m.name) || !["component", "hook", "lib"].includes(kindOf(m))) {
      continue;
    }
    seen.add(m.name);
    notice.push(
      `## ${m.title} (${m.name})`,
      "",
      `- Author: ${m.author}`,
      `- License: ${m.license}`,
    );
    if (m.attribution) {
      notice.push(`- Attribution: ${m.attribution}`);
    }
    notice.push(
      `- Source: ${m.source.repo === "private source" ? "private source" : m.source.repo} @ ${m.source.commit}`,
    );
    notice.push(
      `- Credits: ${m.credits
        .map((c) => {
          const x = credits.get(c);
          return x
            ? `${c} ${x.title} (${x.license}${x.url ? `, ${x.url}` : ""})`
            : c;
        })
        .join("; ")}`,
      "",
    );
  }
  write(join(PKG, "NOTICE.md"), notice.join("\n"));
  const pkgPath = join(PKG, "package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const sorted = Object.fromEntries(
    Object.entries(exportsMap).sort(([a], [b]) => a.localeCompare(b)),
  );
  if (JSON.stringify(pkg.exports) !== JSON.stringify(sorted)) {
    pkg.exports = sorted;
    writeFileSync(pkgPath, json(pkg));
  }

  process.stdout.write(
    `prepare-content: ${data.entries.length} entries, ${published.length} published items, ${entries.length} npm entry points.\n`,
  );
}

main();
