#!/usr/bin/env node
// The source scanner (.github/workflows/scanner.yml, docs/scanner.md).
//
//   node scripts/scan-sources.mjs oss
//     For every active `pinned-git` source in the `oss` section of
//     sources.yaml, fetch each listed registry item at the pinned commit and
//     write it to content/components/<id>/<component>/ with a generated
//     meta.json (author, license, attribution and credit from sources.yaml).
//     Prints the changed paths; the workflow turns them into a pull request.
//
//   node scripts/scan-sources.mjs dispatch <event.json>
//     A `component-export` repository_dispatch from a private source: checks
//     that the source is approved and that the named pull request only
//     touches that source's content (and the citation registry). Prints a
//     Markdown report for the run summary and the pull request.
//
// Private sources are never fetched from here (docs/contract.md, section 7).
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { CONTENT_DIR, loadSources, ROOT } from "./lib/content.mjs";
import { SITE_URL } from "./lib/naming.mjs";

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const STUB_DEMO = `// Generated by the scanner: replace with a real demo before marking ready.
export default function Demo() {
  return <p className="text-muted-foreground text-sm">Demo pending review.</p>;
}
`;

/** The raw URL of a file in a public GitHub repository at a pinned commit. */
export function rawUrl(repo, ref, path) {
  const match = /^https:\/\/github\.com\/([^/]+)\/([^/]+?)(?:\.git)?\/?$/.exec(
    repo,
  );
  if (!match) {
    throw new Error(`only public GitHub repositories are supported: ${repo}`);
  }
  return `https://raw.githubusercontent.com/${match[1]}/${match[2]}/${ref}/${path}`;
}

/** The meta.json the scanner writes for one third-party component. */
export function ossMeta(source, component, items, today) {
  const variants = component.items.map((spec) => ({
    name: spec.variant,
    primitive: spec.primitive ?? "none",
    iconSet: spec.iconSet ?? "none",
    ...(spec.style ? { style: spec.style } : {}),
    status: component.status ?? "beta",
  }));
  const first = items[component.items[0].variant];
  return {
    $schema: `${SITE_URL}/schemas/meta.schema.json`,
    schemaVersion: 1,
    name: component.name,
    kind: "component",
    title: component.title ?? first?.title ?? component.name,
    description:
      component.description ??
      first?.description ??
      `${component.name} from ${source.name}.`,
    status: component.status ?? "beta",
    category: component.category,
    label: source.name,
    variants,
    defaultVariant: component.defaultVariant ?? variants[0].name,
    demo: "demo.tsx",
    preview: "preview.webp",
    source: {
      repo: source.repo,
      commit: source.ref,
      ...(component.path ? { path: component.path } : {}),
    },
    author: source.author,
    license: source.license,
    attribution: source.attribution,
    credits: [source.credit, ...(component.credits ?? [])],
    date: today,
  };
}

async function fetchText(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`);
  }
  return response.text();
}

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current !== content) {
    writeFileSync(path, content);
    return true;
  }
  return false;
}

async function scanOss() {
  const { oss } = loadSources();
  const today = new Date().toISOString().slice(0, 10);
  const changed = [];
  const active = oss.filter(
    (s) => s.status === "active" && s.fetch === "pinned-git",
  );
  for (const source of active) {
    for (const component of source.components ?? []) {
      const dir = join(ROOT, CONTENT_DIR, source.id, component.name);
      const items = {};
      for (const spec of component.items) {
        const text = await fetchText(
          rawUrl(source.repo, source.ref, spec.path),
        );
        const item = JSON.parse(text);
        item.name = spec.variant;
        items[spec.variant] = item;
        if (write(join(dir, "items", `${spec.variant}.json`), json(item))) {
          changed.push(
            `${CONTENT_DIR}/${source.id}/${component.name}/items/${spec.variant}.json`,
          );
        }
      }
      const demo = component.demo
        ? await fetchText(rawUrl(source.repo, source.ref, component.demo))
        : STUB_DEMO;
      if (!existsSync(join(dir, "demo.tsx")) || component.demo) {
        if (write(join(dir, "demo.tsx"), demo)) {
          changed.push(
            `${CONTENT_DIR}/${source.id}/${component.name}/demo.tsx`,
          );
        }
      }
      // Keep the date stable when nothing else changed.
      const metaPath = join(dir, "meta.json");
      const previous = existsSync(metaPath)
        ? JSON.parse(readFileSync(metaPath, "utf8"))
        : null;
      const meta = ossMeta(source, component, items, previous?.date ?? today);
      if (write(metaPath, json(meta))) {
        changed.push(`${CONTENT_DIR}/${source.id}/${component.name}/meta.json`);
      }
    }
  }
  process.stdout.write(
    `scan-sources: ${active.length} active third-party source(s), ${changed.length} changed file(s).\n`,
  );
  for (const path of changed) {
    process.stdout.write(`changed: ${path}\n`);
  }
}

/** Problems with an export pull request's changed paths. */
export function exportScopeProblems(sourceId, paths) {
  const allowed = [`${CONTENT_DIR}/${sourceId}/`, "docs/sources/registry.yaml"];
  return paths
    .filter(
      (path) =>
        !allowed.some((prefix) => path === prefix || path.startsWith(prefix)),
    )
    .map((path) => `outside the export scope: ${path}`);
}

function dispatch(eventPath) {
  const event = JSON.parse(readFileSync(eventPath, "utf8"));
  const payload = event.client_payload ?? {};
  const sources = loadSources();
  const source = sources.byId.get(payload.source);
  const lines = ["## Component export", ""];
  const problems = [];
  if (!source) {
    problems.push(`source "${payload.source}" is not in sources.yaml`);
  } else if (source.section !== "sources" || source.fetch !== "exports-only") {
    problems.push(
      `source "${payload.source}" does not deliver by export pull request`,
    );
  } else if (source.status !== "active") {
    problems.push(`source "${payload.source}" is not active`);
  }
  const pr = Number.parseInt(String(payload.pr ?? ""), 10);
  if (!Number.isInteger(pr) || pr <= 0) {
    problems.push("client_payload.pr must be the export pull request number");
  }
  if (problems.length === 0) {
    const repo = process.env.GITHUB_REPOSITORY;
    const files = execFileSync(
      "gh",
      [
        "pr",
        "view",
        String(pr),
        "-R",
        repo,
        "--json",
        "files,baseRefName,headRefName",
        "--jq",
        ".",
      ],
      { encoding: "utf8" },
    );
    const view = JSON.parse(files);
    const paths = view.files.map((f) => f.path);
    if (view.baseRefName !== "staging") {
      problems.push(
        `the pull request targets ${view.baseRefName}; exports target staging`,
      );
    }
    if (!view.headRefName.startsWith(`export/${payload.source}/`)) {
      problems.push(
        `the branch should be export/${payload.source}/<component>`,
      );
    }
    problems.push(...exportScopeProblems(payload.source, paths));
    lines.push(`Pull request #${pr}: ${paths.length} changed file(s).`, "");
  }
  if (problems.length === 0) {
    lines.push(
      "Scope and source are approved. CI validates the content on the pull request itself (contract, shadcn schema, licenses, guards).",
    );
  } else {
    lines.push("Problems:", "", ...problems.map((p) => `- ${p}`));
  }
  process.stdout.write(`${lines.join("\n")}\n`);
  process.exitCode = problems.length === 0 ? 0 : 1;
}

const [mode, arg] = process.argv.slice(2);
if (import.meta.url === `file://${process.argv[1]}`) {
  if (mode === "oss") {
    await scanOss();
  } else if (mode === "dispatch" && arg) {
    dispatch(arg);
  } else {
    process.stderr.write(
      "usage: scan-sources.mjs oss | dispatch <event.json>\n",
    );
    process.exitCode = 2;
  }
}
